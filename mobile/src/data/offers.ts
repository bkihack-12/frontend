const inDays = (n: number) => {
  const d = addDays(startOfDay(new Date()), n);
  d.setHours(23, 59, 0, 0);
  return d.toISOString();
};

const agoMin = (min: number) => new Date(Date.now() - min * 60000).toISOString();

