/**
 * PRZYKŁADOWE wydarzenia (dane wymyślone na potrzeby prototypu).
 * Daty są liczone względem dzisiejszego dnia, dzięki czemu demo zawsze wygląda aktualnie.
 * Współrzędne są przybliżone. Aby dodać wydarzenie, dopisz obiekt do listy poniżej.
 */
function at(dayOffset: number, hhmm: string, durationH = 2): { startsAt: string; endsAt: string } {
  const [h, m] = hhmm.split(':').map(Number);
  const now = new Date();
  const start = addDays(startOfDay(now), dayOffset);
  start.setHours(h, m, 0, 0);
  // "Today" events whose slot has already passed are moved to tomorrow so the demo never looks stale.
  if (dayOffset === 0 && start.getTime() + durationH * 3600 * 1000 < now.getTime() + 15 * 60000) {
    start.setDate(start.getDate() + 1);
  }
  const end = new Date(start.getTime() + durationH * 3600 * 1000);
  return { startsAt: start.toISOString(), endsAt: end.toISOString() };
}

